import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

async function render() {
  const workerUrl = new URL("../dist/server/index.js", import.meta.url);
  workerUrl.searchParams.set("test", `${process.pid}-${Date.now()}`);
  const { default: worker } = await import(workerUrl.href);
  return worker.fetch(new Request("http://localhost/", { headers: { accept: "text/html" } }), { ASSETS: { fetch: async () => new Response("Not found", { status: 404 }) } }, { waitUntil() {}, passThroughOnException() {} });
}

test("server-renders the Felix Copilot workspace", async () => {
  const response = await render();
  assert.equal(response.status, 200);
  assert.match(response.headers.get("content-type") ?? "", /^text\/html\b/i);
  const html = await response.text();
  assert.match(html, /Felix Copilot/);
  assert.match(html, /Atendimentos/);
  assert.match(html, /RESPOSTA SUGERIDA/);
  assert.match(html, /DADOS DO CHAMADO/);
  assert.doesNotMatch(html, /Your site is taking shape/);
});

test("keeps site-specific metadata and no starter preview", async () => {
  const [page, layout] = await Promise.all([
    readFile(new URL("../app/page.tsx", import.meta.url), "utf8"),
    readFile(new URL("../app/layout.tsx", import.meta.url), "utf8"),
  ]);
  assert.match(layout, /Felix Copilot/);
  assert.doesNotMatch(layout, /codex-preview|_sites-preview/);
  assert.match(page, /Analisar conversa/);
});
